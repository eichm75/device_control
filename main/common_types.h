/*

    Предварительное описание механизма управления устройством.
    Устройство будет состоять из нескольких программно-аппаратных модулей:
        - плата с процессором dsp, задача которой принимать на вход аудиосигнал, обрабатывать его, передавать на усилители. Параллельно, dsp должен
          ракладывать сигнал на частотные полосы, и замерять уровень сигнала в каждой полосе.
        - модуль bluetooth, для приема аудиосигнала с мобильных устройств.
        - модуль радио FM, для приема аудиосигнала с радиостанций.
        - модуль для чтения данных с SD карты, для воспроизведения аудиофайлов.
        - модуль управления LED, для визуализации уровней сигнала в каждой полосе и различной анимации.
    Все эти модули должны управляться через единый интерфейс, который будет принимать команды в виде строк от различных источников.
    Источниками команд могут быть: websocket сервер, сенсорная панель управления на корпусе устройства, пуль ДУ, возможно мобильное приложение.
    Для интерпретации поступающих команд, в интерфейс конкретного модуля, должны быть определены исполнительные функции "драйверы", которые после
    получения командного сообщения, будут распознавать его, выполнять необходимый код и возвращать результат выполнения. 
    
    Предварительное описание структуры входящего сообщения.
    Устройство должно управляться через сообщения, поступающие из различных источников. Например: websocket сервер или сенсорная
    панель управления на корпусе устройства. Сообщение определяется структурой incoming_message_t и должно содержать 
    следующую информацию:
        Поле source - дескриптор источника сообщения. Например: WEB_SERVER или CONTROL_PANEL.
        Поле data - строка, содержащая дескриптор исполнительного модуля, саму команду и 
            необходимые параметры команды, разделенные двоеточиями.
    Соответственно, получается такая структура строки incoming_message_t.data - [executor_id]:[command]:[parameters]
    Максимальная длина каждой части строки ограничивается соответствующими константами. Длина [executor_id] будет всегда
    постоянна, а длина [command] и [parameters] может быть переменной, так как скорей всего, не для всех команд возможно будет
    определить единый формат, но в любом случае, их максимальная длина будет ограничена константами. Возможно в некоторых
    командах, поле [parameters] , будет отсутствовать, тогда строка будет иметь формат [executor_id]:[command]:
    Следующими макросами опредеяются константы, ограничивающие длину каждой части строки data и ее общую длину.
*/
#define EXECUTOR_ID_LENGTH 3
#define COMMAND_LENGTH 15
#define PARAMETERS_LENGTH 6
#define INCOMING_MESSAGE_DATA_LENGTH (EXECUTOR_ID_LENGTH + COMMAND_LENGTH + PARAMETERS_LENGTH + 2) // +2 для разделителей ":"
#define INCOMING_COMMAND_INFO_LENGTH (COMMAND_LENGTH + PARAMETERS_LENGTH + 1) // +1 для разделителя ":"

// источник поступившего сообщения
typedef enum {
    UNKNOWN_SOURCE = 0,
    WEB_SERVER,
    CONTROL_PANEL
} source_message_t;

// структура для хранения информации о сообщении, которая включает в себя источник сообщения, идентификатор клиента и данные сообщения
typedef struct {
    source_message_t source; // источник сообщения
    char data[INCOMING_MESSAGE_DATA_LENGTH]; // данные сообщения
} incoming_message_t;

// структура для хранения информации о команде и ее параметре
typedef struct {
    char command[COMMAND_LENGTH]; // команда
    char parameters[PARAMETERS_LENGTH]; // параметр команды
} incoming_command_info_t;

